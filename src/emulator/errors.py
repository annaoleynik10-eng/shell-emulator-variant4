"""Исключения, которые используются внутри эмулятора."""


class ShellError(Exception):
    """Ошибка выполнения команды: сообщение выводится пользователю."""


class ShellExit(Exception):
    """Запрос на завершение работы эмулятора (команда exit)."""

    def __init__(self, code):
        """Сохранить код завершения."""
        super().__init__(code)
        self.code = code
